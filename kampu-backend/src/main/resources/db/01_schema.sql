CREATE TABLE USUARIOS_SISTEMA (
    usuario_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR2(50) NOT NULL UNIQUE,
    password_hash VARCHAR2(255) NOT NULL,
    rol VARCHAR2(50) NOT NULL,
    estado VARCHAR2(20) DEFAULT 'ACTIVO'
);

CREATE TABLE CLIENTES (
    cliente_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_completo VARCHAR2(150) NOT NULL,
    tipo_documento VARCHAR2(20) NOT NULL,
    numero_documento VARCHAR2(20) NOT NULL UNIQUE,
    email VARCHAR2(100),
    telefono VARCHAR2(20)
);

CREATE TABLE GUIAS (
    guia_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_completo VARCHAR2(150) NOT NULL,
    especialidad VARCHAR2(100),
    telefono VARCHAR2(20)
);

CREATE TABLE TRANSPORTE (
    transporte_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    placa VARCHAR2(15) NOT NULL UNIQUE,
    marca_modelo VARCHAR2(100),
    capacidad NUMBER(3) NOT NULL
);

CREATE TABLE PAQUETES_TOUR (
    paquete_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR2(100) NOT NULL,
    descripcion VARCHAR2(1000),
    precio_base NUMBER(10,2) NOT NULL,
    dias NUMBER(2) NOT NULL,
    noches NUMBER(2) NOT NULL,
    imagen VARCHAR2(500),
    estado VARCHAR2(20) DEFAULT 'ACTIVO'
)
STORAGE (
  INITIAL 640K
  NEXT 640K
  MINEXTENTS 3
);

CREATE TABLE SALIDAS_PROGRAMADAS (
    salida_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paquete_id NUMBER NOT NULL,
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE NOT NULL,
    cupos_maximos NUMBER(3) NOT NULL,
    cupos_disponibles NUMBER(3) NOT NULL,
    guia_id NUMBER,
    transporte_id NUMBER,
    estado VARCHAR2(20) DEFAULT 'PROGRAMADA',
    CONSTRAINT chk_salida_fechas CHECK (fecha_fin >= fecha_inicio),
    CONSTRAINT chk_salida_cupos CHECK (cupos_maximos > 0 AND cupos_disponibles >= 0 AND cupos_disponibles <= cupos_maximos),
    CONSTRAINT chk_salida_estado CHECK (estado IN ('PROGRAMADA', 'CONFIRMADA', 'COMPLETADA', 'CANCELADA')),
    CONSTRAINT fk_salida_paquete FOREIGN KEY (paquete_id) REFERENCES PAQUETES_TOUR(paquete_id),
    CONSTRAINT fk_salida_guia FOREIGN KEY (guia_id) REFERENCES GUIAS(guia_id),
    CONSTRAINT fk_salida_transporte FOREIGN KEY (transporte_id) REFERENCES TRANSPORTE(transporte_id)
)
STORAGE (
  INITIAL 640K
  NEXT 640K
  MINEXTENTS 3
);

CREATE TABLE RESERVAS (
    reserva_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id NUMBER NOT NULL,
    salida_id NUMBER NOT NULL,
    fecha_reserva TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    numero_viajeros NUMBER(2) NOT NULL,
    monto_total NUMBER(10,2) NOT NULL,
    monto_pagado NUMBER(10,2) DEFAULT 0,
    estado_reserva VARCHAR2(20) DEFAULT 'PENDIENTE',
    estado_pago VARCHAR2(20) DEFAULT 'PENDIENTE',
    observaciones VARCHAR2(200),
    forma_reembolso VARCHAR2(50),
    usuario_anula_id NUMBER,
    CONSTRAINT chk_res_viajeros CHECK (numero_viajeros > 0),
    CONSTRAINT chk_res_monto_total CHECK (monto_total > 0),
    CONSTRAINT chk_res_monto_pagado CHECK (monto_pagado >= 0 AND monto_pagado <= monto_total),
    CONSTRAINT chk_res_estado CHECK (estado_reserva IN ('PENDIENTE', 'CONFIRMADA', 'ANULADA', 'COMPLETADA')),
    CONSTRAINT chk_res_estado_pago CHECK (estado_pago IN ('PENDIENTE', 'PARCIAL', 'PAGADO', 'REEMBOLSADO')),
    CONSTRAINT fk_reserva_cliente FOREIGN KEY (cliente_id) REFERENCES CLIENTES(cliente_id),
    CONSTRAINT fk_reserva_salida FOREIGN KEY (salida_id) REFERENCES SALIDAS_PROGRAMADAS(salida_id),
    CONSTRAINT fk_reserva_usuario FOREIGN KEY (usuario_anula_id) REFERENCES USUARIOS_SISTEMA(usuario_id)
)
STORAGE (
  INITIAL 1M
  NEXT 1M
  MINEXTENTS 3
);

CREATE TABLE PASAJEROS_RESERVA (
    pasajero_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reserva_id NUMBER NOT NULL,
    nombre_completo VARCHAR2(150) NOT NULL,
    tipo_documento VARCHAR2(20) NOT NULL,
    numero_documento VARCHAR2(20) NOT NULL,
    nacionalidad VARCHAR2(50),
    fecha_nacimiento DATE,
    CONSTRAINT chk_pas_tipo_doc CHECK (tipo_documento IN ('DNI', 'CE', 'PASAPORTE')),
    CONSTRAINT uq_pas_reserva_doc UNIQUE (reserva_id, numero_documento),
    CONSTRAINT fk_pasajero_reserva FOREIGN KEY (reserva_id) REFERENCES RESERVAS(reserva_id)
)
STORAGE (
  INITIAL 640K
  NEXT 640K
  MINEXTENTS 3
);

CREATE TABLE PAGOS (
    pago_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reserva_id NUMBER NOT NULL,
    monto NUMBER(10,2) NOT NULL,
    moneda VARCHAR2(10) DEFAULT 'PEN',
    metodo_pago VARCHAR2(50),
    codigo_transaccion VARCHAR2(100),
    fecha_pago TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    estado_transaccion VARCHAR2(20),
    CONSTRAINT chk_pago_monto CHECK (monto > 0),
    CONSTRAINT chk_pago_moneda CHECK (moneda IN ('PEN', 'USD', 'EUR')),
    CONSTRAINT chk_pago_estado CHECK (estado_transaccion IN ('PENDIENTE', 'APROBADO', 'RECHAZADO', 'REEMBOLSADO')),
    CONSTRAINT fk_pago_reserva FOREIGN KEY (reserva_id) REFERENCES RESERVAS(reserva_id)
)
STORAGE (
  INITIAL 640K
  NEXT 640K
  MINEXTENTS 3
);

CREATE OR REPLACE TRIGGER TRG_PAS_FECHA_NAC
BEFORE INSERT OR UPDATE OF fecha_nacimiento ON PASAJEROS_RESERVA
FOR EACH ROW
WHEN (NEW.fecha_nacimiento IS NOT NULL)
BEGIN
    IF :NEW.fecha_nacimiento >= TRUNC(SYSDATE) THEN
        RAISE_APPLICATION_ERROR(-20001, 'chk_pas_fecha_nac: la fecha de nacimiento debe ser anterior a hoy.');
    END IF;
END;
